    <script>
        document.addEventListener('DOMContentLoaded', () => {
            const counters = document.querySelectorAll('.counter');
            const speed = 200; // Velocidad de la animación (menor es más rápido)

            const animateCounters = (entries, observer) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        const counter = entry.target;
                        const target = +counter.getAttribute('data-target');
                        
                        const updateCount = () => {
                            const current = +counter.innerText.replace(/,/g, '');
                            const inc = target / speed;

                            if (current < target) {
                                // Añade separador de miles dinámicamente
                                counter.innerText = Math.ceil(current + inc).toLocaleString('en-US');
                                setTimeout(updateCount, 15);
                            } else {
                                // Se asegura de poner el '+' al final de la cifra mayor
                                counter.innerText = target.toLocaleString('en-US') + (target > 50000 ? '+' : '');
                            }
                        };
                        updateCount();
                        // Dejamos de observar una vez completada la animación
                        observer.unobserve(counter);
                    }
                });
            };

            const counterObserver = new IntersectionObserver(animateCounters, {
                threshold: 0.5 // Se activa cuando el 50% de la sección es visible
            });

            counters.forEach(counter => {
                counterObserver.observe(counter);
            });
        });
    </script>

