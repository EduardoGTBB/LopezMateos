<script>
    document.addEventListener('DOMContentLoaded', function() {
        const searchInput = document.getElementById('searchInput');
        const accordionItems = document.querySelectorAll('.accordion-item');

        if (searchInput) {
            searchInput.addEventListener('input', function(e) {
                // Obtenemos el texto ingresado, lo pasamos a minúsculas y le quitamos los acentos (NFD)
                const term = e.target.value.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

                accordionItems.forEach(function(item) {
                    // Tomamos todo el texto de la tarjeta (pregunta + respuesta), minúsculas y sin acentos
                    const textContent = item.textContent.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
                    
                    // Si el texto incluye lo que buscamos, mostramos la tarjeta; si no, la ocultamos
                    if (textContent.includes(term)) {
                        item.style.display = ''; 
                    } else {
                        item.style.display = 'none'; 
                    }
                });
            });
        }
    });
</script> 

